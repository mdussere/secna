"""Build presentation/data.js — the real LangChain run, one particle per pull request.

Usage (from the repo root, with the notebook's virtual environment):
    notebook/.venv/bin/python presentation/tools/build_data.py \
        notebook/data/langchain_2026-07-23_2026-10-23/corpus.parquet presentation/data.js

Reads the run's output (one row per pull request: embedding, cluster, theme, dates, origin) and
writes a compact JavaScript file the talk loads offline:
  - a 3-D map of the 768-dimension embeddings (normalised, reduced to 50 dimensions, then laid out
    in 3-D so that pull requests with similar texts sit close together);
  - per pull request: cluster, theme, day of creation, a few flags (bot, signatures);
  - per cluster: size, theme, month-by-month counts, the five pull requests nearest its centre.
No title, description, name, author or URL is written — only positions and numbers.
"""
import base64
import json
import sys

import numpy as np
import pandas as pd
from sklearn.decomposition import PCA
from sklearn.manifold import TSNE

SRC, OUT = sys.argv[1], sys.argv[2]
START = pd.Timestamp("2026-07-23", tz="Europe/Paris")
MONTHS = [pd.Timestamp("2026-08-23", tz="Europe/Paris"), pd.Timestamp("2026-09-23", tz="Europe/Paris")]

df = pd.read_parquet(SRC, columns=[
    "createdAt", "author_bot", "origin", "description", "title", "repo",
    "embedding", "cluster", "centroid_distance", "theme", "theme_name"])
df = df.sort_values("createdAt", kind="stable").reset_index(drop=True)
n = len(df)

# --- 3-D map of the embeddings -------------------------------------------------------------
X = np.stack(df["embedding"].to_numpy()).astype(np.float32)
X /= np.linalg.norm(X, axis=1, keepdims=True)
X50 = PCA(n_components=50, random_state=0).fit_transform(X)
Y = TSNE(n_components=3, perplexity=40, init="pca", learning_rate="auto",
         max_iter=1000, random_state=0).fit_transform(X50)
Y -= np.median(Y, axis=0)
Y /= np.quantile(np.linalg.norm(Y, axis=1), 0.995)   # 99.5 % of the points inside the unit sphere
Y = np.clip(Y, -1.2, 1.2)
pos = np.round(Y / 1.2 * 32767).astype("<i2")

# --- per pull request -----------------------------------------------------------------------
created = df["createdAt"].dt.tz_convert("Europe/Paris")
day = ((created - START).dt.total_seconds() // 86400).clip(0, 255).astype("u1").to_numpy()
desc = df["description"].fillna("")
flags = (df["author_bot"].to_numpy().astype("u1")
         | (df["origin"].str.contains("agent").to_numpy().astype("u1") << 1)
         | (desc.str.contains(r"made by.*open swe", case=False, regex=True).to_numpy().astype("u1") << 2)
         | (desc.str.contains("Opened from a [LangSmith Engine issue](", regex=False).to_numpy().astype("u1") << 3))
month = np.select([created < MONTHS[0], created < MONTHS[1]], [0, 1], 2)

themes = (df.groupby(["theme", "theme_name"]).size().reset_index(name="n")
          .sort_values("n", ascending=False).reset_index(drop=True))
theme_index = {t: i for i, t in enumerate(themes["theme"])}
th = df["theme"].map(theme_index).astype("u1").to_numpy()
cl = df["cluster"].astype("u1").to_numpy()

clusters = []
for c, g in df.groupby("cluster"):
    idx = g.index.to_numpy()
    clusters.append({
        "c": int(c), "t": theme_index[g["theme"].iloc[0]], "n": int(len(g)),
        "m": [int((month[idx] == k).sum()) for k in range(3)],
        "repos": int(g["repo"].nunique()),
        # the five pull requests nearest the centre (indices into the particle order)
        "core": [int(i) for i in g.sort_values("centroid_distance").index[:5]],
    })

# a few pull requests the talk points at (indices into the particle order)
def find(title_start):
    hit = df.index[df["title"].str.startswith(title_start, na=False)]
    return int(hit[0]) if len(hit) else -1

special = {"nbS": find("fix: flush pipeline before checkpoint operations")}

b64 = lambda a: base64.b64encode(np.ascontiguousarray(a).tobytes()).decode()
data = {
    "n": n, "days": int(day.max()) + 1,
    "pos": b64(pos), "cl": b64(cl), "th": b64(th), "day": b64(day), "fl": b64(flags),
    "themes": [{"id": r.theme, "name": r.theme_name, "n": int(r.n),
                "k": int(df.loc[df["theme"] == r.theme, "cluster"].nunique()),
                "repos": int(df.loc[df["theme"] == r.theme, "repo"].nunique())}
               for r in themes.itertuples()],
    "clusters": clusters, "special": special,
}
with open(OUT, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/build_data.py from the LangChain run — do not edit.\n")
    f.write("window.SECNA_DATA=" + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(f"{n} pull requests · {len(clusters)} clusters · {len(themes)} themes → {OUT}")
